export const ORBIT_COMPONENTS_LIST = Object.keys(components);

export default function OrbitComponentTester() {
  const { componentName } = useParams();

  if (!componentName || !components[componentName]) {
    return (
      <div className="p-10 text-center flex flex-col items-center justify-center min-h-[50vh]">
        <h2 className="text-xl font-semibold">Component Not Found</h2>
        <p className="text-[#71717a] dark:text-gray-400 mt-2">Please select a valid component from the Orbit Build dropdown.</p>
      </div>
    );
  }

  const ComponentToRender = components[componentName];

  return (
    <Suspense fallback={
      <div className="flex items-center justify-center h-full min-h-[50vh]">
        <OrbitLoader size="md" />
      </div>
    }>
      <ComponentToRender pageName={componentName} title={componentName} />
    </Suspense>
  );
}

